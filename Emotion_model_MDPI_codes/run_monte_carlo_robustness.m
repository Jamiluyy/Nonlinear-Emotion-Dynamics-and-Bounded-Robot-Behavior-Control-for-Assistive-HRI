%% run_monte_carlo_robustness.m
% Expanded Monte Carlo robustness assessment for the nonlinear emotion model.
% Scenario 2 is used because repeated unclear reminders provide the more
% demanding interaction condition among the original manuscript scenarios.
%
% The nominal LQR gain is retained in every trial. Therefore, this study
% evaluates empirical performance under parameter uncertainty rather than
% retuning the controller for each perturbed model.

clear; clc; close all;

thisFolder = fileparts(mfilename('fullpath'));
if isempty(thisFolder)
    thisFolder = pwd;
end
addpath(thisFolder);

if exist('lqr', 'file') ~= 2
    error(['The function lqr was not found. Install or enable the ', ...
        'MATLAB Control System Toolbox before running this script.']);
end

outputFolder = fullfile(thisFolder, 'validation_results');
if ~exist(outputFolder, 'dir')
    mkdir(outputFolder);
end

%% 1. Study settings
scenarioId = 2;
numberOfTrials = 200;
uncertaintyLevel = 0.20;
randomSeed = 20261022;

% A response is treated as bounded when all simulated states are finite
% and remain within the normalised range used in this study.
stateBound = 1.0;

% A command is treated as saturated when it reaches either physical bound.
saturationTolerance = 1e-8;

rng(randomSeed, 'twister');

%% 2. Nominal model and fixed LQR controller
pNominal = emotion_model_parameters(scenarioId);
[~, ~, pNominal.Klqr, ~] = design_lqr_controller(pNominal);

adverseIndices = [2, 3, 4, 6];
adverseNames = pNominal.emotionNames(adverseIndices);

%% 3. Preallocate trial-level results
openLoopPeak = zeros(numberOfTrials, 1);
lqrPeak = zeros(numberOfTrials, 1);

openLoopIAE = zeros(numberOfTrials, 1);
lqrIAE = zeros(numberOfTrials, 1);

peakReductionPercent = zeros(numberOfTrials, 1);
iaeReductionPercent = zeros(numberOfTrials, 1);

minimumHappinessOpenLoop = zeros(numberOfTrials, 1);
minimumHappinessLQR = zeros(numberOfTrials, 1);

controlEffortLQR = zeros(numberOfTrials, 1);
saturationPercent = zeros(numberOfTrials, 1);
maximumStateMagnitude = zeros(numberOfTrials, 1);

boundedResponse = false(numberOfTrials, 1);

%% 4. Monte Carlo simulations
for trial = 1:numberOfTrials

    % Each nonzero model parameter is independently multiplied by a
    % uniformly distributed factor in [0.80, 1.20].
    pTrial = perturb_emotion_parameters(pNominal, uncertaintyLevel);

    % Retain the nominal controller gain. No trial-specific retuning occurs.
    pTrial.Klqr = pNominal.Klqr;

    trialResult = simulate_emotion_case(pTrial);

    % Aggregate peak adverse-emotion deviation.
    openLoopPeak(trial) = max(max(trialResult.xFree(:, adverseIndices)));
    lqrPeak(trial) = max(max(trialResult.xLqr(:, adverseIndices)));

    % Aggregate integrated absolute deviation of adverse emotions.
    openLoopIAE(trial) = sum(trapz(trialResult.tFree, ...
        abs(trialResult.xFree(:, adverseIndices))));

    lqrIAE(trial) = sum(trapz(trialResult.tLqr, ...
        abs(trialResult.xLqr(:, adverseIndices))));

    % Improvement relative to the corresponding open-loop trial.
    peakReductionPercent(trial) = 100 * ...
        (openLoopPeak(trial) - lqrPeak(trial)) / ...
        max(openLoopPeak(trial), eps);

    iaeReductionPercent(trial) = 100 * ...
        (openLoopIAE(trial) - lqrIAE(trial)) / ...
        max(openLoopIAE(trial), eps);

    % Happiness protection and control effort.
    minimumHappinessOpenLoop(trial) = min(trialResult.xFree(:, 1));
    minimumHappinessLQR(trial) = min(trialResult.xLqr(:, 1));
    controlEffortLQR(trial) = trialResult.metrics.controlEffort;

    % Percentage of time samples where at least one physical command
    % reaches a lower or upper bound.
    commandAtBound = any( ...
        trialResult.uLqr <= saturationTolerance | ...
        trialResult.uLqr >= 1 - saturationTolerance, 2);

    saturationPercent(trial) = 100 * mean(commandAtBound);

    % Maximum absolute state magnitude across open- and closed-loop runs.
    maximumStateMagnitude(trial) = max(abs( ...
        [trialResult.xFree(:); trialResult.xLqr(:)]));

    boundedResponse(trial) = ...
        all(isfinite(trialResult.xFree(:))) && ...
        all(isfinite(trialResult.xLqr(:))) && ...
        maximumStateMagnitude(trial) <= stateBound;
end

%% 5. Trial-level table
trialNumber = (1:numberOfTrials).';

trialTable = table(trialNumber, openLoopPeak, lqrPeak, ...
    peakReductionPercent, openLoopIAE, lqrIAE, iaeReductionPercent, ...
    minimumHappinessOpenLoop, minimumHappinessLQR, controlEffortLQR, ...
    saturationPercent, maximumStateMagnitude, boundedResponse, ...
    'VariableNames', ...
    {'Trial', 'OpenLoopPeakAdverseEmotion', 'LQRPeakAdverseEmotion', ...
     'PeakReductionPercent', 'OpenLoopAdverseEmotionIAE', ...
     'LQRAdverseEmotionIAE', 'IAEReductionPercent', ...
     'MinimumHappinessOpenLoop', 'MinimumHappinessLQR', ...
     'LQRControlEffort', 'SaturationPercent', ...
     'MaximumStateMagnitude', 'BoundedResponse'});

writetable(trialTable, fullfile(outputFolder, ...
    'monte_carlo_trial_results.csv'));

%% 6. Summary statistics
metricNames = { ...
    'Peak adverse-emotion deviation'; ...
    'Aggregate adverse-emotion IAE'; ...
    'Peak reduction relative to open loop (%)'; ...
    'IAE reduction relative to open loop (%)'; ...
    'Minimum happiness under LQR'; ...
    'LQR control effort'; ...
    'Command saturation (%)'; ...
    'Maximum absolute state magnitude'};

meanValue = [ ...
    mean(lqrPeak); ...
    mean(lqrIAE); ...
    mean(peakReductionPercent); ...
    mean(iaeReductionPercent); ...
    mean(minimumHappinessLQR); ...
    mean(controlEffortLQR); ...
    mean(saturationPercent); ...
    mean(maximumStateMagnitude)];

standardDeviation = [ ...
    std(lqrPeak); ...
    std(lqrIAE); ...
    std(peakReductionPercent); ...
    std(iaeReductionPercent); ...
    std(minimumHappinessLQR); ...
    std(controlEffortLQR); ...
    std(saturationPercent); ...
    std(maximumStateMagnitude)];

minimumValue = [ ...
    min(lqrPeak); ...
    min(lqrIAE); ...
    min(peakReductionPercent); ...
    min(iaeReductionPercent); ...
    min(minimumHappinessLQR); ...
    min(controlEffortLQR); ...
    min(saturationPercent); ...
    min(maximumStateMagnitude)];

maximumValue = [ ...
    max(lqrPeak); ...
    max(lqrIAE); ...
    max(peakReductionPercent); ...
    max(iaeReductionPercent); ...
    max(minimumHappinessLQR); ...
    max(controlEffortLQR); ...
    max(saturationPercent); ...
    max(maximumStateMagnitude)];

summaryTable = table(metricNames, meanValue, standardDeviation, ...
    minimumValue, maximumValue, ...
    'VariableNames', ...
    {'Metric', 'Mean', 'StandardDeviation', 'Minimum', 'Maximum'});

writetable(summaryTable, fullfile(outputFolder, ...
    'monte_carlo_summary_statistics.csv'));

%% 7. Boundedness and improvement-success summary
boundedResponseRatePercent = 100 * mean(boundedResponse);
peakImprovementRatePercent = 100 * mean(peakReductionPercent > 0);
iaeImprovementRatePercent = 100 * mean(iaeReductionPercent > 0);
anySaturationRatePercent = 100 * mean(saturationPercent > 0);

statusTable = table(numberOfTrials, uncertaintyLevel, randomSeed, ...
    stateBound, boundedResponseRatePercent, peakImprovementRatePercent, ...
    iaeImprovementRatePercent, anySaturationRatePercent, ...
    'VariableNames', ...
    {'NumberOfTrials', 'UncertaintyLevel', 'RandomSeed', ...
     'StateBound', 'BoundedResponseRatePercent', ...
     'PeakImprovementRatePercent', 'IAEImprovementRatePercent', ...
     'AnySaturationRatePercent'});

writetable(statusTable, fullfile(outputFolder, ...
    'monte_carlo_status_summary.csv'));

%% 8. Distribution figure
figure('Color', 'w', 'Position', [100 100 1100 720]);
tiledlayout(2, 2, 'TileSpacing', 'compact', 'Padding', 'compact');

nexttile;
boxplot([openLoopPeak, lqrPeak], ...
    'Labels', {'Open loop', 'Saturated LQR'});
ylabel('Peak adverse-emotion deviation');
title('Peak adverse-emotion response');
grid on;

nexttile;
boxplot([openLoopIAE, lqrIAE], ...
    'Labels', {'Open loop', 'Saturated LQR'});
ylabel('Aggregate adverse-emotion IAE');
title('Integrated adverse-emotion response');
grid on;

nexttile;
boxplot(peakReductionPercent);
ylabel('Peak reduction (%)');
title('Peak-response improvement');
grid on;

nexttile;
boxplot(iaeReductionPercent);
ylabel('IAE reduction (%)');
title('Integrated-response improvement');
grid on;

exportgraphics(gcf, fullfile(outputFolder, ...
    'monte_carlo_robustness_distributions.png'), ...
    'Resolution', 300);

%% 9. Command-window summary
fprintf('\nMonte Carlo robustness assessment\n');
fprintf('Scenario: %d\n', scenarioId);
fprintf('Trials: %d\n', numberOfTrials);
fprintf('Independent uniform parameter uncertainty: +/- %.0f%%\n', ...
    100 * uncertaintyLevel);
fprintf('Random seed: %d\n', randomSeed);
fprintf('Adverse emotions included: %s, %s, %s, and %s\n', ...
    adverseNames{1}, adverseNames{2}, adverseNames{3}, adverseNames{4});

fprintf('\nRobustness-status summary:\n');
disp(statusTable);

fprintf('\nSummary statistics:\n');
disp(summaryTable);

fprintf('\nFiles exported to:\n%s\n', outputFolder);